def geog_normalization(geog):
	geog_mapping = {
		'mpo': 'MPO',
		'county': 'County Name',
		'msa': 'MSA',
		'metro': 'MSA',
		'tract': 'tract'
	}
	geog_normalized = geog.lower()
	geog_agg_col = geog_mapping.get(geog_normalized)
	if geog_agg_col is None:
		print('Invalid geog provided')
		exit()  
	return geog_normalized, geog_agg_col



